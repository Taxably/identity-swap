"""Write names.js: the first names and surnames people in the United States carry, for the
identity swap page.

    python make_names.py <dist.female.first> <dist.male.first> <names.zip> <baby-names.csv> <words_alpha.txt>

Every input is checked against the SHA-256 below before anything is read from it:

* dist.female.first, dist.male.first: the Census Bureau's 1990 first-name tables
  (www2.census.gov/topics/genealogy/1990surnames/), public domain.
* names.zip: the Census Bureau's 2010 surname table (www2.census.gov/topics/genealogy/2010surnames/),
  public domain. Every surname held by 100 or more people, ranked.
* baby-names.csv: the Social Security Administration's top 1,000 baby names for every year from
  1880 to 2008 (a copy of the SSA's public-domain tables, raw.githubusercontent.com/hadley/
  data-baby-names), for the first names the 1990 tables are too old to carry.
* words_alpha.txt: the English word list of github.com/dwyl/english-words (the Unlicense). It only
  marks which names are also English words ("Brown", "Page", "Self"), so the page never takes a
  word for a name on the word alone.

The page uses the lists two ways: a word on them is evidence of a person's name (with the line
around it reading as a name), and a stand-in is a real name from them, as popular as a person a
reader might meet. Nothing is added to the public tables and nothing is taken out of them beyond
the rules below, so the same inputs always give the same names.js.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PINS = {
    "female": "bd2f310fc4e5d5e5ea122c9d4342c9821145823118eb20db1647f305ec77b358",
    "male": "0a5078ef6effe3b483d15b0f7f95047662126c9bfb624ecd5e5b978fc0f2470b",
    "surnames": "117c41cb4668727b7627b2845b6df3f83eb2a22a1813f42c0ff4bdcab86de135",
    "ssa": "1259523fa76e5c18151a4c7612b854b22605d07127c596126940e2941ba15d3c",
    "words": "3ed0c94610d8bcf7c11bbb49c56aa49c7234d32b66824df91f554169e572da48",
}
SURNAMES = 50000  # the 50,000 most common surnames: held by about 250 people or more each

def pinned(path: str, key: str) -> bytes:
    with open(path, "rb") as fh:
        data = fh.read()
    got = hashlib.sha256(data).hexdigest()
    if got != PINS[key]:
        raise SystemExit("%s is not the pinned %s file (sha256 %s)" % (path, key, got))
    return data


def cap(name: str) -> str:
    """A name as people write it: Smith, McDonald, Delacruz."""
    low = name.lower()
    if low.startswith("mc") and len(low) > 3:
        return "Mc" + low[2].upper() + low[3:]
    return low[:1].upper() + low[1:]


def main() -> int:
    female_path, male_path, zip_path, ssa_path, words_path = sys.argv[1:6]
    words = set(pinned(words_path, "words").decode("utf-8").split())

    # first names: how popular each is, from the SSA's years and the 1990 census together
    score = {"F": {}, "M": {}}
    for row in csv.DictReader(io.StringIO(pinned(ssa_path, "ssa").decode("utf-8"))):
        sex = "F" if row["sex"] == "girl" else "M"
        score[sex][row["name"]] = score[sex].get(row["name"], 0.0) + float(row["percent"])
    for sex, key, path in (("F", "female", female_path), ("M", "male", male_path)):
        for line in pinned(path, key).decode("latin-1").splitlines():
            parts = line.split()
            if len(parts) >= 2:
                name = cap(parts[0])
                # a 1990 share in percent, weighed like about a decade of SSA years
                score[sex][name] = score[sex].get(name, 0.0) + float(parts[1]) / 10
    # a name both sexes carry goes to both only when neither has it far more often
    first = {}
    for sex, other in (("F", "M"), ("M", "F")):
        keep = [n for n, s in score[sex].items() if s >= score[other].get(n, 0.0) / 3]
        first[sex] = sorted(keep, key=lambda n: -score[sex][n])

    with zipfile.ZipFile(io.BytesIO(pinned(zip_path, "surnames"))) as z:
        rows = list(csv.DictReader(io.StringIO(z.read("Names_2010Census.csv").decode("latin-1"))))
    last = [cap(r["name"]) for r in sorted(rows, key=lambda r: int(r["rank"])) if r["name"] != "ALL OTHER NAMES"][:SURNAMES]

    clean = lambda names: [n for n in names if n.isalpha() and len(n) >= 2]
    female, male, last = clean(first["F"]), clean(first["M"]), clean(last)
    word = sorted({n.lower() for n in female + male + last if n.lower() in words})
    out = {"female": " ".join(female), "male": " ".join(male), "last": " ".join(last), "word": " ".join(word)}
    text = "globalThis.PDFSWAP_NAMES = " + json.dumps(out, separators=(",", ":")) + ";\n"
    with open(os.path.join(HERE, "names.js"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by make_names.py from the Census Bureau's and the SSA's public-domain name tables.\n")
        fh.write(text)
    print("names.js: %d female, %d male first names, %d surnames, %d also English words, %d bytes"
          % (len(female), len(male), len(last), len(word), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
